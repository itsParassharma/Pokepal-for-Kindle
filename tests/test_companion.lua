local E=dofile(BASE..'/engine.lua')
local R=dofile(BASE..'/reading.lua')
local S=dofile(BASE..'/storage.lua')
local now=1800000000
local passed=0
local function test(name,fn) fn();passed=passed+1;print('PASS '..name) end
local function pet()
 local s=E.new(now);E.act(s,'choose',4,now);R.init(s);return s
end
test('recap reports new minutes and progress without paying twice',function()
 local s=pet();E.act(s,'egg',nil,now);E.act(s,'readingtrip',1,now)
 local message,recap=E.readingReward(s,600,now)
 assert(message and recap.seconds==600 and recap.berries==1 and recap.xp==0 and recap.events[1]=='Berry patch')
 assert(recap.trip_before==0 and recap.trip_after==600 and recap.egg_after==600)
 local _,next=E.readingReward(s,300,now)
 assert(next.berries==1 and next.xp==6 and next.trip_before==600 and next.trip_after==900)
 local berries,xp=s.berries,s.xp;local _,empty=E.readingReward(s,0,now)
 assert(not empty and s.berries==berries and s.xp==xp)
end)
test('first scan and disabled reading do not create a recap',function()
 local s=pet();local _,recap=R.collect(s,E,{},3600,now);assert(not recap)
 s.reading.enabled=false;_,recap=R.collect(s,E,{},7200,now+3600);assert(not recap)
 s.reading.enabled=true;_,recap=R.collect(s,E,{},8100,now+4500);assert(recap.seconds==900)
end)
test('weekly goals start from new time and pay once across target changes',function()
 local s=pet();E.readingReward(s,7200,now);E.act(s,'goal',7200,now)
 assert(s.week.seconds==0 and not s.week.claimed)
 E.readingReward(s,3600,now);local berries,xp=s.berries,s.xp
 E.act(s,'goal',3600,now);assert(s.week.claimed and s.berries==berries+5 and s.xp==xp+10)
 E.act(s,'goal',10800,now);E.readingReward(s,7200,now)
 assert(s.berries==berries+13 and s.xp==xp+34)
 s=S.decode(S.encode(s),E);assert(s and s.week.claimed and s.week.seconds==10800)
end)
test('a new week resets only its goal and clock rollback cannot replay the bonus',function()
 local s=pet();E.act(s,'goal',3600,now);local start=s.week.start
 local _,recap=E.readingReward(s,3600,now);assert(recap.weekly and recap.berries==9 and recap.xp==22)
 E.advance(s,start-86400);assert(s.week.claimed and s.week.start==start)
 local nextweek=start+8*86400;E.advance(s,nextweek)
 assert(not s.week.claimed and s.week.seconds==0 and s.reading.seconds==3600 and s.week.target==3600)
 E.readingReward(s,3600,nextweek);assert(s.week.claimed)
end)
test('weekly state rejects malformed goals and duplicate records',function()
 local data=S.encode(pet())
 for _,line in ipairs({'week=1,0,0,false','week=3600,0,0,maybe','week=3600,-1,0,false',
  'week=3600,0,1000000000001,false','week=3600,0,0,false\nweek=3600,0,0,false'}) do assert(not S.decode(data..line..'\n',E)) end
end)
test('decorations charge once and remember ownership when hidden',function()
 local s=pet();s.berries=100
 for id,item in ipairs(E.decorations) do
  local before=s.berries;E.act(s,'decorate',id,now);assert(s.decor[id] and s.berries==before-item.cost)
  E.act(s,'decorate',id,now);assert(s.decor[id]==false and s.berries==before-item.cost)
  s=S.decode(S.encode(s),E);E.act(s,'decorate',id,now);assert(s.decor[id] and s.berries==before-item.cost)
 end
 assert(s.berries==65);E.act(s,'background',6,now);assert(s.decor[1] and s.decor[4])
end)
test('decorations reject unknown items, bad saves and insufficient berries',function()
 local s=pet();E.act(s,'decorate',4,now);assert(s.berries==6 and not s.decor[4])
 E.act(s,'decorate',99,now);assert(s.berries==6)
 local data=S.encode(s)
 for _,line in ipairs({'decor=0,true','decor=5,true','decor=1,yes','decor=1,false\ndecor=1,true'}) do assert(not S.decode(data..line..'\n',E)) end
end)
test('discoveries arrive at quarter milestones and never pay twice after reload',function()
 local s=pet();E.act(s,'readingtrip',1,now)
 E.readingReward(s,449,now);assert(s.finds==0 and s.berries==6)
 E.readingReward(s,1,now);assert(s.finds==1 and s.berries==7)
 s=S.decode(S.encode(s),E);E.advance(s,now);assert(s.finds==1 and s.berries==7)
 E.readingReward(s,450,now);assert(s.finds==2 and s.xp==6)
 local energy=s.energy;E.readingReward(s,450,now);assert(s.finds==3 and s.energy==energy+8)
 E.readingReward(s,450,now);local berries,xp=s.berries,s.xp;E.act(s,'collect',nil,now)
 assert(s.berries==berries+3 and s.xp==xp+12 and not s.finds)
end)
test('timed milestones work without reading, and old trips keep their original rewards',function()
 local s=pet();E.act(s,'trip',1,now);E.advance(s,now+450);assert(s.finds==1)
 E.advance(s,now+449);assert(s.finds==1 and s.berries==7)
 local old=pet();old.trip=1;old.due=now+1800
 E.act(old,'collect',nil,now+1800);assert(old.berries==9 and old.xp==12)
 local data=S.encode(pet());assert(not S.decode(data..'finds=1\n',E))
end)
test('nicknames survive switches, evolution and save reloads',function()
 local s=pet();E.act(s,'nickname','  Ember  ',now);assert(E.displayName(s)=='Ember')
 s.seen['25']=true;E.act(s,'partner',25,now);E.act(s,'nickname','Sparky',now)
 E.act(s,'partner',4,now);assert(E.displayName(s)=='Ember')
 s.xp=300;s.bond=30;E.act(s,'evolve',nil,now);assert(s.species==5 and E.displayName(s)=='Ember')
 s=S.decode(S.encode(s),E);assert(s and E.displayName(s)=='Ember')
 E.act(s,'nickname','',now);assert(E.displayName(s)==E.name(5) and s.nicknames['25']=='Sparky')
end)
test('nicknames reject unsafe or unsupported text without changing the name',function()
 local s=pet();E.act(s,'nickname','Pal',now)
 for _,name in ipairs({'1234567890123','hello\nworld','name=bad','caf'..string.char(195,169)}) do E.act(s,'nickname',name,now);assert(E.displayName(s)=='Pal') end
 local data=S.encode(pet())
 for _,line in ipairs({'nickname=999,Pal','nickname=25,Pal','nickname=4,Pal\nnickname=4,Other','nickname=4, space','nickname=4,1234567890123'}) do assert(not S.decode(data..line..'\n',E)) end
end)
test('partner reactions follow care and bond and use the nickname',function()
 local s=pet();E.act(s,'nickname','Ember',now);local neutral=E.reaction(s)
 s.bond=80;assert(E.reaction(s)~=neutral and E.reaction(s):find('Ember',1,true))
 s.food=20;assert(E.reaction(s):find('basket',1,true))
 s.resting=true;assert(E.reaction(s):find('curled up',1,true))
end)
test('away reactions report the trail until the partner returns',function()
 for _,action in ipairs({'trip','readingtrip'}) do
  local s=pet();E.act(s,'nickname','Ember',now);E.act(s,action,1,now)
  local message=E.act(s,'check',nil,now)
  assert(message:find('Ember is exploring Meadow',1,true))
  if action=='trip' then s.due=now else E.readingReward(s,1800,now) end
  assert(E.act(s,'check',nil,now):find('Your partner is back',1,true))
 end
end)

test('timed trip recap compares the last visit with current progress',function()
 local s=pet();E.act(s,'trip',1,now)
 local _,recap=E.readingReward(s,300,now+900)
 assert(recap.trip_before==0 and recap.trip_after==900)
 assert(E.tripLeft(s,now-3600)==1800)
end)
