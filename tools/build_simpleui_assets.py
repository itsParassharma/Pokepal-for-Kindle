"""Derive Tiny Critter stills from PokePal's existing packed animation assets."""
import argparse
import io
import json
from pathlib import Path

from lupa.luajit21 import LuaRuntime
from PIL import Image

REPO = Path(__file__).resolve().parents[1]
PLUGIN = REPO / "pokepal.koplugin"


def build():
    lua = LuaRuntime(unpack_returned_tuples=True)
    spec = lua.execute(f'return dofile("{PLUGIN.as_posix()}/simpleui_critter.lua")')
    moods = list(spec.moods.values())
    source_index = json.loads((PLUGIN / "assets/sprite-index.json").read_text())
    packed, seen, entries = bytearray(), {}, []
    for species in range(1, 387):
        frames = {}
        for mood in moods:
            pose = spec.poses[mood]
            name = f"{species}-{pose}.png"
            if name not in source_index:
                name = f"{species}-idle-1.png"
            part, offset, length = source_index[name]
            with (PLUGIN / "assets" / f"{part:03}.bin").open("rb") as f:
                f.seek(offset)
                image = Image.open(io.BytesIO(f.read(length))).convert("LA")
                image.load()
            frames[mood] = image
        # Use the same crop and scale for all moods of this species. Keep every
        # opaque source pixel within the crop; sprites retain their proportions.
        boxes = [image.getchannel("A").getbbox() for image in frames.values()]
        assert all(boxes), species
        box = (min(b[0] for b in boxes), min(b[1] for b in boxes),
               max(b[2] for b in boxes), max(b[3] for b in boxes))
        scale = min(1, 64 / max(box[2] - box[0], box[3] - box[1]))
        size = (max(1, round((box[2] - box[0]) * scale)),
                max(1, round((box[3] - box[1]) * scale)))
        row = []
        for mood in moods:
            image = frames[mood].crop(box).resize(size, Image.Resampling.NEAREST)
            # A common 64px canvas and no transparent foot keeps SimpleUI's
            # existing widget geometry valid after an exported image changes.
            foot = image.getchannel("A").getbbox()[3]
            tile = Image.new("LA", (64, 64), (255, 0))
            tile.paste(image, ((64 - size[0]) // 2, 64 - foot))
            data = io.BytesIO()
            tile.save(data, format="PNG", optimize=False, compress_level=9)
            png = data.getvalue()
            if png not in seen:
                seen[png] = (len(packed), len(png))
                packed.extend(png)
            offset, length = seen[png]
            row.append(f"{mood}={{{offset},{length}}}")
        entries.append(f" [{species}]={{{','.join(row)}}},\n")
    index = "-- Generated by tools/build_simpleui_assets.py; existing sprite licences apply.\nreturn {\n" + "".join(entries) + "}\n"
    return {"index.lua": index.encode(), "sprites.bin": bytes(packed)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify committed assets without changing them")
    args = parser.parse_args()
    output = PLUGIN / "assets/simpleui"
    for name, data in build().items():
        path = output / name
        if args.check:
            assert path.read_bytes() == data, f"Regenerate {path}"
        else:
            output.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    print("Tiny Critter: 386 Pokemon, 12 moods each; reproducible 64 x 64 PNG stills")


if __name__ == "__main__":
    main()
